#!/usr/bin/env bash
#
# Builds every Peter project in every configuration using the portable
# MSVC 6.0 command line tools under Wine.
#
# Intended to run inside the container built from Containerfile.wine, with the
# repository mounted at /workspace:
#
#   wslc build -t peter-wine -f .\Containerfile.wine .
#   wslc run --rm -v "C:\path\to\Peter:/workspace" peter-wine bash /workspace/build-wine.sh
#
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/Peter250src"

# Build one project configuration. nmake runs from the project directory so the
# relative paths in the .mak files resolve. NO_EXTERNAL_DEPS=1 skips the
# checked-in .dep files: CI always builds from a clean tree, and a few of them
# are stale after the refactors.
build() {
    local dir="$1" mak="$2" cfg="$3"
    echo
    echo "===== $dir/$mak  [$cfg] ====="
    ( cd "$root/$dir" && wine nmake /f "$mak" NO_EXTERNAL_DEPS=1 "CFG=$cfg" )
}

# The readme says: build DelExe first, then the rest alphabetically from top to
# bottom, with Loader before Peter.
build DelExe    DelExe.mak   "DelExe - Win32 Release"
build DelExe    DelExe.mak   "DelExe - Win32 Debug"

build DataInst  DataInst.mak "DataInst - Win32 Release"
build DataInst  DataInst.mak "DataInst - Win32 Debug"

build Gener     Gener.mak    "Gener - Win32 Release"
build Gener     Gener.mak    "Gener - Win32 Release MINI"
build Gener     Gener.mak    "Gener - Win32 Install"
build Gener     Gener.mak    "Gener - Win32 Debug"

build Loader    Peter.mak    "Loader - Win32 Release"
build Loader    Peter.mak    "Loader - Win32 Release Mini"
build Loader    Peter.mak    "Loader - Win32 Debug"
build Loader    Peter.mak    "Loader - Win32 Debug Optim"

build Loader0   Peter.mak    "Loader0 - Win32 Release"
build Loader0   Peter.mak    "Loader0 - Win32 Debug"

build Peter     Peter.mak    "Peter - Win32 Release"
build Peter     Peter.mak    "Peter - Win32 Debug"
build Peter     Peter.mak    "Peter - Win32 Debug Optim"

build Pov2Spr   Pov2Spr.mak  "Pov2Spr - Win32 Release"
build Pov2Spr   Pov2Spr.mak  "Pov2Spr - Win32 Debug"

# NOTE: the Setup installer project is intentionally not built here. Its
# Resource.rc needs the Res\*.bmp files generated by Setup\Res\Source\!Konv.bat,
# which runs the DOS tool alchemy.exe and cannot run in this container.

# Make sure no Wine daemon is left running once the build is done.
wineserver -w

echo
echo "All projects built."
